#!/usr/bin/env python3
"""Push the per-ABI bootstrap archives into a dedicated release tag.

The workflow runs this with the app's own token, so the archives survive cache eviction
and can be downloaded by anyone (including from inside a restricted sandbox) with a
plain GET on the release asset URL.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path


def gh(*args: str) -> str:
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="bootstrap-cache")
    ap.add_argument("--title", default="Termux bootstrap (prefix-patched)")
    ap.add_argument("--jni-libs", required=True)
    args = ap.parse_args()

    files = sorted(Path(args.jni_libs).glob("*/libtermux-bootstrap.so"))
    if not files:
        print("no bootstrap archives found; nothing to publish", file=sys.stderr)
        return 0

    existing = subprocess.run(["gh", "release", "view", args.tag],
                              capture_output=True, text=True)
    if existing.returncode != 0:
        gh("release", "create", args.tag,
           "--title", args.title,
           "--notes", "Per-ABI Termux bootstrap with the compiled-in prefix rewritten for "
                      "io.rea.ide. Generated by CI from scripts/prepare_bootstrap.py.")

    # Rename on upload so the asset name carries the ABI.
    for f in files:
        abi = f.parent.name
        target = f"{args.tag}-{abi}.zip"
        subprocess.run(["gh", "release", "upload", args.tag, str(f),
                        "--clobber", "--rename", target], check=True)
        print(f"uploaded {target}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
